class PasswordsController < ApplicationController
  allow_unauthenticated_access
  before_action :set_user_by_token, only: %i[ edit update ]
  rate_limit to: 10, within: 3.minutes, only: :create, with: -> { redirect_to new_password_path, alert: "Trop de tentatives, réessaie dans quelques minutes." }

  def new
  end

  def create
    if user = User.find_by(email_address: params[:email_address])
      PasswordsMailer.reset(user).deliver_later
    end

    redirect_to new_session_path, notice: "Si un compte existe à cette adresse, un lien pour changer le mot de passe vient d'y être envoyé."
  end

  def edit
  end

  def update
    if @user.update(params.permit(:password, :password_confirmation))
      @user.sessions.destroy_all
      redirect_to new_session_path, notice: "Mot de passe changé. Tu peux te connecter."
    else
      redirect_to edit_password_path(params[:token]), alert: "Les deux mots de passe ne correspondent pas."
    end
  end

  private
    def set_user_by_token
      @user = User.find_by_password_reset_token!(params[:token])
    rescue ActiveSupport::MessageVerifier::InvalidSignature
      redirect_to new_password_path, alert: "Ce lien n'est plus valable. Demandes-en un nouveau."
    end
end
